"""Collect verified public-domain artworks from The Met into app/art-list.js.

Requests are sequential and spaced out to stay under the API's burst limits.
Usage: python -I build_art_list.py <output art-list.js>
"""
import json
import random
import sys
import time
import urllib.parse
import urllib.request

STYLES = {
    'japanese': ['Hiroshige', 'Hokusai', 'Kawase Hasui', 'ukiyo-e', 'Utamaro', 'Kuniyoshi'],
    'impressionism': ['Degas', 'Cezanne', 'Pissarro', 'Monet', 'Renoir', 'Manet', 'Van Gogh', 'Gauguin', 'Seurat', 'Morisot'],
    'landscapes': ['Hudson River School', 'Bierstadt', 'Frederic Edwin Church', 'Thomas Cole', 'Corot', 'Constable', 'Turner', 'seascape'],
    'classics': ['Vermeer', 'Rembrandt', 'El Greco', 'Velazquez', 'Titian', 'Caravaggio', 'Goya', 'Rubens'],
}
PER_STYLE = 60
KEEP = {'Paintings', 'Prints', 'Drawings'}
API = 'https://collectionapi.metmuseum.org/public/collection'


def get(url, attempt=0):
    req = urllib.request.Request(url, headers={'User-Agent': 'Mozilla/5.0 (ambient-art-list)'})
    try:
        with urllib.request.urlopen(req, timeout=30) as res:
            return json.load(res)
    except urllib.error.HTTPError as e:
        if e.code in (403, 429) and attempt < 4:
            time.sleep(30 * (attempt + 1))
            return get(url, attempt + 1)
        raise


def collect(style, queries):
    found, seen = [], set()
    per_query = max(8, PER_STYLE // len(queries) + 4)
    for q in queries:
        base = API + '/v1.1/search?hasImages=true&isPublicDomain=true&q=' + urllib.parse.quote(q)
        try:
            ids = get(base + '&limit=80')['objectIDs'] or []
        except Exception as e:
            print('search failed', q, e, flush=True)
            continue
        random.shuffle(ids)
        got = 0
        for oid in ids:
            if got >= per_query or len(found) >= PER_STYLE:
                break
            if oid in seen:
                continue
            seen.add(oid)
            time.sleep(0.35)
            try:
                o = get(API + '/v1/objects/%d' % oid)
            except Exception as e:
                print('object failed', oid, e, flush=True)
                continue
            if not (o.get('isPublicDomain') and o.get('primaryImageSmall') and o.get('classification') in KEEP):
                continue
            found.append({
                'id': oid,
                'small': o['primaryImageSmall'],
                'large': o.get('primaryImage') or o['primaryImageSmall'],
                'title': o.get('title', ''),
                'by': ', '.join(x for x in [o.get('artistDisplayName', ''), o.get('objectDate', '')] if x),
            })
            got += 1
        print(style, q, 'kept', got, 'total', len(found), flush=True)
        if len(found) >= PER_STYLE:
            break
    return found


def main():
    out = sys.argv[1]
    data = {}
    for style, queries in STYLES.items():
        data[style] = collect(style, queries)
    with open(out, 'w', encoding='utf-8') as f:
        f.write('// Curated public-domain works from The Metropolitan Museum of Art Open Access.\n')
        f.write('// Generated by build_art_list.py; images load straight from images.metmuseum.org.\n')
        f.write('window.AmbientArt = ' + json.dumps(data, ensure_ascii=False, indent=1) + ';\n')
    print('done', {k: len(v) for k, v in data.items()}, flush=True)


if __name__ == '__main__':
    main()
